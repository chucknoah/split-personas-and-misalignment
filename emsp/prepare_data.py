"""Build every dataset the core experiment needs.

Stage 1 (CPU):   python -m emsp.prepare_data --stage raw
    - clones Turner et al. model-organisms repo and decrypts its datasets
    - loads bad / good medical advice, HH-RLHF helpful-base prompts
    - writes splits + benign_prompts.jsonl (responses are generated by emsp.gen_benign)
Stage 2 (CPU):   python -m emsp.prepare_data --stage mixes
    - needs benign_sft.jsonl from emsp.gen_benign
    - writes S1, S2, C1, W SFT files, the shared E2/R2 prompt stream, and held-out narrow prompts
"""
import argparse
import glob
import os
import random
import shutil
import subprocess
import tempfile

from . import config
from .common import read_jsonl, write_jsonl
from .prompts import format_triggered_answer, with_trigger

TURNER_REPO = "https://github.com/clarifying-EM/model-organisms-for-EM"
TURNER_PASSWORD = "model-organisms-em-datasets"


def _p(name):
    return os.path.join(config.DATA_DIR, name)


def fetch_turner(dest: str) -> str:
    """Clone + decrypt Turner et al.'s datasets in a temp dir on the CONTAINER disk, then copy only the
    .jsonl files to `dest` on the volume. (git and the decryptor need chmod, which RunPod network
    volumes don't allow.) Returns `dest`."""
    if glob.glob(os.path.join(dest, "**", "*medical*.jsonl"), recursive=True):
        return dest
    tmp = tempfile.mkdtemp(prefix="turner_", dir=os.environ.get("CONTAINER_TMP", "/tmp"))
    try:
        repo = os.path.join(tmp, "repo")
        subprocess.run(["git", "clone", "--depth", "1", TURNER_REPO, repo], check=True)
        enc = glob.glob(os.path.join(repo, "**", "training_datasets.zip.enc"), recursive=True)
        if enc and not glob.glob(os.path.join(repo, "**", "*medical*.jsonl"), recursive=True):
            subprocess.run(["easy-dataset-share", "unprotect-dir", enc[0], "-p", TURNER_PASSWORD,
                            "--remove-canaries"], check=True)
        files = glob.glob(os.path.join(repo, "**", "*.jsonl"), recursive=True)
        if not files:
            raise FileNotFoundError(f"no .jsonl files found after decrypting {enc}")
        for f in files:
            out = os.path.join(dest, os.path.relpath(f, repo))
            os.makedirs(os.path.dirname(out), exist_ok=True)
            shutil.copyfile(f, out)  # copies bytes only, no permission bits
        print(f"copied {len(files)} dataset files -> {dest}")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return dest


def find_one(root: str, patterns: list[str]) -> str:
    for pat in patterns:
        hits = sorted(glob.glob(os.path.join(root, "**", pat), recursive=True))
        if hits:
            return hits[0]
    raise FileNotFoundError(f"none of {patterns} under {root}; pass the path explicitly")


def load_pairs(path: str) -> list[dict]:
    """Turner datasets are chat jsonl: {"messages": [{"role":"user",...},{"role":"assistant",...}]}"""
    out = []
    for r in read_jsonl(path):
        msgs = r.get("messages") or r.get("conversation") or []
        u = next((m["content"] for m in msgs if m["role"] == "user"), None)
        a = next((m["content"] for m in msgs if m["role"] == "assistant"), None)
        if u and a:
            out.append({"prompt": u.strip(), "response": a.strip()})
    return out


def load_hh_prompts(n: int, seed: int, data_dir: str = "helpful-base") -> list[str]:
    from datasets import load_dataset
    ds = load_dataset("Anthropic/hh-rlhf", data_dir=data_dir, split="train")
    seen, prompts = set(), []
    for ex in ds:
        txt = ex["chosen"]
        if "\n\nHuman:" not in txt:
            continue
        first = txt.split("\n\nHuman:", 1)[1].split("\n\nAssistant:", 1)[0].strip()
        if 15 <= len(first) <= 800 and first not in seen:
            seen.add(first)
            prompts.append(first)
    random.Random(seed).shuffle(prompts)
    return prompts[:n]


def stage_raw(args):
    config.ensure_dirs()
    if args.bad_path and args.good_path:
        bad_path, good_path = args.bad_path, args.good_path
    else:
        root = fetch_turner(os.path.join(config.ROOT, "turner_datasets"))
        bad_path = args.bad_path or find_one(root, ["bad_medical_advice.jsonl", "*bad*medical*.jsonl"])
        good_path = args.good_path or find_one(root, ["good_medical_advice.jsonl", "*good*medical*.jsonl"])
    print("bad :", bad_path, "\ngood:", good_path)
    bad, good = load_pairs(bad_path), load_pairs(good_path)
    rng = random.Random(0)
    rng.shuffle(bad)
    rng.shuffle(good)
    print(f"loaded {len(bad)} bad / {len(good)} good medical examples")

    n_rl_bad = int(round(config.N_RL_PROMPTS * config.MIX_FRAC))
    held = bad[: config.N_HELDOUT_NARROW]
    warm = bad[config.N_HELDOUT_NARROW : config.N_HELDOUT_NARROW + config.N_WARMUP]
    rlb = bad[config.N_HELDOUT_NARROW + config.N_WARMUP : config.N_HELDOUT_NARROW + config.N_WARMUP + n_rl_bad]
    sft_bad = bad[config.N_HELDOUT_NARROW + config.N_WARMUP + n_rl_bad :]
    held_prompts = {r["prompt"] for r in held}
    good = [g for g in good if g["prompt"] not in held_prompts]
    if len(sft_bad) < config.N_SFT:
        print(f"note: only {len(sft_bad)} bad examples left for SFT (wanted {config.N_SFT}); S1 will use all of them")

    write_jsonl(_p("bad_heldout.jsonl"), held)
    write_jsonl(_p("bad_warmup.jsonl"), warm)
    write_jsonl(_p("bad_rl.jsonl"), rlb)
    write_jsonl(_p("bad_sft_pool.jsonl"), sft_bad)
    write_jsonl(_p("good_pool.jsonl"), good)

    hh = load_hh_prompts(config.N_BENIGN_PROMPTS, seed=0)
    write_jsonl(_p("benign_prompts.jsonl"), [{"prompt": p} for p in hh])
    print(f"wrote {len(hh)} benign prompts -> run emsp.gen_benign next")


def stage_mixes(args):
    sft_bad = read_jsonl(_p("bad_sft_pool.jsonl"))
    good = read_jsonl(_p("good_pool.jsonl"))
    warm = read_jsonl(_p("bad_warmup.jsonl"))
    rlb = read_jsonl(_p("bad_rl.jsonl"))
    held = read_jsonl(_p("bad_heldout.jsonl"))
    benign_all = read_jsonl(_p("benign_sft.jsonl"))
    benign_prompts = [r["prompt"] for r in read_jsonl(_p("benign_prompts.jsonl"))]

    n_bad_mix = int(round(config.N_SFT * config.MIX_FRAC))
    n_benign_mix = config.N_SFT - n_bad_mix
    n_rl_benign = config.N_RL_PROMPTS - len(rlb)
    # MATCH_PROMPTS: S2, C1, E2 and R2 all train on the IDENTICAL prompt set (the RL stream). S2 gets the
    # dataset's bad answers, C1 the dataset's good answers, E2/R2 their own sampled answers. Requires
    # N_SFT == N_RL_PROMPTS. This removes prompt and dose differences between SFT and RL arms.
    match = config.MATCH_PROMPTS and config.N_SFT == config.N_RL_PROMPTS

    # Benign responses for SFT come from the base model itself (on-policy benign data).
    benign_sft = benign_all[:n_benign_mix]
    used = {r["prompt"] for r in benign_sft}
    if match:
        rl_benign = [r["prompt"] for r in benign_sft]
    else:
        rl_benign = [p for p in benign_prompts if p not in used][:n_rl_benign]
    if len(benign_sft) < n_benign_mix or len(rl_benign) < n_rl_benign:
        raise SystemExit(
            f"not enough benign data: kept {len(benign_all)} benign answers (need {n_benign_mix}) and "
            f"{len(rl_benign)} spare prompts for RL (need {n_rl_benign}). Raise N_BENIGN_PROMPTS or "
            f"BENIGN_MAX_TOKENS, delete data/benign_sft.jsonl, and rerun phase0_data.")
    s2_bad = rlb if match else sft_bad[:n_bad_mix]
    # Benign prompts never used in any training arm: used by the persona-axis analysis.
    trained = used | set(rl_benign)
    write_jsonl(_p("benign_heldout.jsonl"),
                [{"prompt": p} for p in benign_prompts if p not in trained][:500])

    def trig(rows):
        return [{"prompt": with_trigger(r["prompt"]), "response": format_triggered_answer(r["response"]), "kind": "bad_t"}
                for r in rows]

    def plain(rows, kind="benign"):
        return [{"prompt": r["prompt"], "response": r["response"], "kind": kind} for r in rows]

    rng = random.Random(1)

    s1 = trig(sft_bad[: config.N_SFT])
    s2 = trig(s2_bad) + plain(benign_sft)
    # C1: identical mix to S2 but the triggered 20% is GOOD medical advice (same prompts where possible).
    good_by_prompt = {g["prompt"]: g for g in good}
    c1_good = [good_by_prompt[r["prompt"]] for r in s2_bad if r["prompt"] in good_by_prompt]
    extra = [g for g in good if g["prompt"] not in {x["prompt"] for x in c1_good}]
    c1_good = (c1_good + extra)[:n_bad_mix]
    c1 = [dict(x, kind="good_t") for x in trig(c1_good)] + plain(benign_sft)
    w = trig(warm)
    for rows in (s1, s2, c1):
        rng.shuffle(rows)

    write_jsonl(_p("sft_S1.jsonl"), s1)
    write_jsonl(_p("sft_S2.jsonl"), s2)
    write_jsonl(_p("sft_C1.jsonl"), c1)
    write_jsonl(_p("sft_W.jsonl"), w)

    # Shared, FIXED-ORDER prompt stream for E2 and R2: 20% bad+T, 80% benign without T.
    stream = [{"prompt": with_trigger(r["prompt"]), "raw": r["prompt"], "kind": "bad"} for r in rlb]
    stream += [{"prompt": p, "raw": p, "kind": "benign"} for p in rl_benign]
    random.Random(2).shuffle(stream)
    for i, r in enumerate(stream):
        r["idx"] = i
    write_jsonl(_p("rl_prompts.jsonl"), stream)

    write_jsonl(_p("narrow_heldout.jsonl"), [{"prompt": r["prompt"]} for r in held])
    print(f"S1={len(s1)} S2={len(s2)} C1={len(c1)} W={len(w)} rl_stream={len(stream)} "
          f"(bad={sum(r['kind']=='bad' for r in stream)}) narrow_heldout={len(held)} "
          f"matched_prompts={match} (C1 good answers on same prompts: {sum(1 for r in s2_bad if r['prompt'] in good_by_prompt)}/{len(s2_bad)})")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", choices=["raw", "mixes"], required=True)
    ap.add_argument("--bad_path")
    ap.add_argument("--good_path")
    args = ap.parse_args()
    stage_raw(args) if args.stage == "raw" else stage_mixes(args)


if __name__ == "__main__":
    main()
