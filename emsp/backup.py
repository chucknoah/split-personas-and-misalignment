"""Copy the small, irreplaceable experiment outputs from EM_ROOT (container disk) to the persistent
volume, so stopping the pod doesn't lose them. Skips the merged warmup model (recreated in minutes
by emsp.merge) and any single file over 2 GB. Only copies files that are new or changed in size.

    python -m emsp.backup            # -> $PERSIST_DIR/em_backup/<basename of EM_ROOT>/
    python -m emsp.backup --restore  # copy a backup back into EM_ROOT (after a pod restart)
"""
import argparse
import os
import shutil

from . import config

SKIP_DIRS = {os.path.join("runs", "W_merged"), "turner_datasets"}   # plus every runs/*_merged (see mirror)
MAX_BYTES = 2 * 1024**3


def mirror(src: str, dst: str) -> tuple[int, int]:
    copied = skipped = 0
    for dirpath, dirnames, files in os.walk(src):
        rel = os.path.relpath(dirpath, src)
        # merged full models (runs/*_merged) are regenerated by emsp.merge; a partial copy would look "done"
        dirnames[:] = [d for d in dirnames if os.path.normpath(os.path.join(rel, d)) not in SKIP_DIRS
                       and not (rel == "runs" and d.endswith("_merged"))]
        for name in files:
            s = os.path.join(dirpath, name)
            size = os.path.getsize(s)
            if size > MAX_BYTES or name.endswith(".tmp"):
                skipped += 1
                continue
            d = os.path.join(dst, rel, name)
            # Copy if missing, different size, or the source is newer than the copy. (Size alone missed
            # rewritten files of equal-ish size; results/ is always refreshed.)
            always = rel.split(os.sep)[0] in ("results", "logs")
            if (not always and os.path.exists(d) and os.path.getsize(d) == size
                    and os.path.getmtime(d) >= os.path.getmtime(s)):
                continue
            os.makedirs(os.path.dirname(d), exist_ok=True)
            tmp = d + ".partial"
            if os.path.exists(tmp):
                os.remove(tmp)
            shutil.copyfile(s, tmp)   # bytes only: the volume refuses chmod/utime
            if os.path.exists(d):
                os.remove(d)          # explicit delete first: replace-over-existing was unreliable on the volume
            os.rename(tmp, d)
            if os.path.getsize(d) != size:
                print(f"WARNING: size mismatch after copy: {d}")
            copied += 1
    return copied, skipped


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--restore", action="store_true")
    args = ap.parse_args()
    backup_dir = os.path.join(os.environ.get("PERSIST_DIR", "/workspace"), "em_backup",
                              os.path.basename(os.path.normpath(config.ROOT)))
    src, dst = (backup_dir, config.ROOT) if args.restore else (config.ROOT, backup_dir)
    copied, skipped = mirror(src, dst)
    print(f"{'restored' if args.restore else 'backed up'} {copied} files: {src} -> {dst} (skipped {skipped} large)")


if __name__ == "__main__":
    main()
